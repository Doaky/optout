"""In-memory broker catalog, populated from the brokers/ YAML directory.

Bundled definitions are loaded strictly. Two user-controlled layers are loaded
leniently (a bad file is reported, not fatal) and win over the bundled set:

1. ``<data dir>/imported/``   generated by ``optout brokers import``
2. ``<config dir>/brokers.d/``  hand-written fixes and additions

``<config dir>/overrides.yml`` then enables or disables brokers by slug.
"""

from __future__ import annotations

import os
import re
from importlib.resources import files
from pathlib import Path

import yaml

from ..config import config_dir
from ..db import db_path
from .loader import load_all_brokers, load_broker
from .schema import BrokerDef

_registry: dict[str, BrokerDef] = {}
_loaded = False
load_errors: list[str] = []


def _brokers_dir() -> Path:
    """Return the directory containing broker YAML files.

    Priority:
    1. OPTOUT_BROKERS_DIR env var — lets users/tests override with a custom set.
    2. importlib.resources — finds the YAMLs bundled inside the installed package,
       works for both editable installs (real filesystem path) and wheel installs.
    """
    env = os.environ.get("OPTOUT_BROKERS_DIR")
    if env:
        return Path(env)
    return Path(str(files("optout").joinpath("data/brokers")))


def imported_dir() -> Path:
    return db_path().parent / "imported"


def user_dir() -> Path:
    return config_dir() / "brokers.d"


def overrides_path() -> Path:
    return config_dir() / "overrides.yml"


def load_overrides() -> dict[str, list[str]]:
    path = overrides_path()
    data = yaml.safe_load(path.read_text()) if path.exists() else None
    data = data if isinstance(data, dict) else {}
    return {k: sorted({str(x) for x in data.get(k) or []}) for k in ("enabled", "disabled")}


def set_enabled(slug: str, enabled: bool) -> None:
    ov = load_overrides()
    ov["enabled"] = [s for s in ov["enabled"] if s != slug]
    ov["disabled"] = [s for s in ov["disabled"] if s != slug]
    ov["enabled" if enabled else "disabled"].append(slug)
    path = overrides_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump({k: sorted(v) for k, v in ov.items()}))
    if slug in _registry:  # take effect now, not at the next reload
        _registry[slug] = _registry[slug].model_copy(update={"enabled": enabled})


def _load_lenient(directory: Path) -> list[BrokerDef]:
    found: list[BrokerDef] = []
    if not directory.exists():
        return found
    for yml in sorted(directory.glob("*.yml")):
        try:
            found.append(load_broker(yml))
        except (ValueError, yaml.YAMLError) as exc:
            load_errors.append(f"{yml.name}: {str(exc).splitlines()[0]}")
    return found


_AUTOMATION = (
    "category",
    "method",
    "opt_out_url",
    "required_fields",
    "optional_fields",
    "requires_listing_url",
    "requires_phone_verification",
    "requires_email_verification",
    "requires_id_upload",
    "requires_notarization",
    "re_add_window_days",
    "last_verified_at",
    "scan",
    "steps",
)


def _keep_automation(bundled: BrokerDef, imported: BrokerDef) -> BrokerDef:
    keep = {k: getattr(bundled, k) for k in _AUTOMATION}
    notes = " ".join(x for x in (bundled.notes or "", imported.notes or "") if x).strip()
    return imported.model_copy(update={**keep, "notes": notes or None})


def _shared_list(name: str) -> list:
    try:
        data = yaml.safe_load(files("optout").joinpath(f"data/{name}").read_text())
    except (OSError, yaml.YAMLError):
        return []
    return data if isinstance(data, list) else []


def _add_extra_brokers(merged: dict[str, BrokerDef]) -> dict[str, BrokerDef]:
    """Brokers from other public lists (data/extra_brokers.yml) that the loaded registry
    doesn't already have, matched by slug, contact email, or domain. Bad entries are skipped."""
    emails = {(b.opt_out_email or "").lower() for b in merged.values()}
    domains = {b.domain.lower().removeprefix("www.") for b in merged.values()}
    for item in _shared_list("extra_brokers.yml"):
        try:
            b = BrokerDef.model_validate(item)
        except (ValueError, TypeError):
            continue
        email, domain = (b.opt_out_email or "").lower(), b.domain.lower().removeprefix("www.")
        if b.slug in merged or email in emails or domain in domains:
            continue
        merged[b.slug] = b
        emails.add(email)
        domains.add(domain)
    return merged


def _apply_form_links(merged: dict[str, BrokerDef]) -> dict[str, BrokerDef]:
    """Fill in a broker's opt-out form link from data/form_links.yml when it has none."""
    for item in _shared_list("form_links.yml"):
        if not isinstance(item, dict):
            continue
        slug, url = str(item.get("broker", "")), str(item.get("url", ""))
        b = merged.get(slug)
        if b is not None and not b.opt_out_url and url.startswith("https://"):
            merged[slug] = b.model_copy(update={"opt_out_url": url})
    return merged


_NEEDS = {
    "listing_url": "requires_listing_url",
    "email_verify": "requires_email_verification",
    "phone_verify": "requires_phone_verification",
    "id_upload": "requires_id_upload",
    "account": "requires_account",
    "payment": "requires_payment",
}


def _site(host: str) -> str:
    parts = host.lower().removeprefix("www.").split(".")
    return ".".join(parts[-2:])


def _apply_people_search(merged: dict[str, BrokerDef]) -> dict[str, BrokerDef]:
    """People-search sites (data/people_search.yml): update the broker with the same domain,
    or add it. They're done through their own form, so they leave the email queue."""
    by_site: dict[str, list[str]] = {}
    for slug, b in merged.items():
        hosts = {
            _site(h) for h in (b.domain, (b.opt_out_email or "").rsplit("@", 1)[-1]) if "." in h
        }
        for host in hosts:
            by_site.setdefault(host, []).append(slug)
    for item in _shared_list("people_search.yml"):
        if not isinstance(item, dict) or not item.get("domain") or not item.get("name"):
            continue
        domain = str(item["domain"]).lower()
        needs = {str(n) for n in item.get("needs") or []}
        category = str(item.get("category", "people_search"))
        update: dict = {
            "priority": int(item.get("priority", 3)),
            "category": category,
            **{flag: key in needs for key, flag in _NEEDS.items()},
        }
        if category == "people_search":
            # Their public-listing opt-out is open to anyone, whatever a registry exemption
            # says about state deletion rights. (Your own "never contact" still wins.)
            update["enabled"] = True
        form_only = category == "people_search"  # their own form, not email
        for key in ("opt_out_url", "search_url"):
            if str(item.get(key, "")).startswith("https://"):
                update[key] = str(item[key])
        if item.get("email") and category == "people_search":
            update["opt_out_email"] = str(item["email"])
        notes = str(item.get("notes", "")).strip()
        covers = [str(c) for c in item.get("covers") or []]
        slugs = by_site.get(_site(domain), [])
        try:
            for slug in slugs:  # every broker on that site: one company, one form
                b = merged[slug]
                note = " ".join(x for x in (notes, b.notes or "") if x)[:1000] or None
                # An automated web form we already have stays; only email moves to the queue.
                method = "manual" if form_only and b.method == "email" else b.method
                merged[slug] = BrokerDef.model_validate(
                    {
                        **b.model_dump(),
                        **update,
                        "method": method,
                        "notes": note,
                        "covers": b.covers + covers,
                    }
                )
            if not slugs:
                new_slug = re.sub(r"[^a-z0-9]+", "-", domain.split(".")[0]).strip("-")
                while new_slug in merged:
                    new_slug += "-site"
                merged[new_slug] = BrokerDef.model_validate(
                    {
                        "slug": new_slug,
                        "name": str(item["name"]),
                        "domain": domain,
                        "method": "manual",
                        "legal_basis": ["CCPA"],
                        "statutory_response_days": 45,
                        "source": "people-search-list",
                        "notes": notes or None,
                        "covers": covers,
                        **update,
                    }
                )
                by_site[_site(domain)] = [new_slug]
        except (ValueError, TypeError):
            continue
    return merged


def _apply_aliases(merged: dict[str, BrokerDef]) -> dict[str, BrokerDef]:
    """Other names a broker's emails go out under (data/broker_aliases.yml), so a reply from a
    shared platform (OneTrust...) that names the parent or brand still finds the request."""
    for item in _shared_list("broker_aliases.yml"):
        if not isinstance(item, dict):
            continue
        b = merged.get(str(item.get("broker", "")))
        names = [str(n) for n in item.get("names") or [] if str(n).strip()]
        if b is not None and names:
            merged[b.slug] = b.model_copy(
                update={"covers": b.covers + [n for n in names if n not in b.covers]}
            )
    return merged


def load_registry(brokers_dir: Path | None = None) -> None:
    global _registry, _loaded
    load_errors.clear()
    explicit = brokers_dir or (
        Path(os.environ["OPTOUT_BROKERS_DIR"]) if os.environ.get("OPTOUT_BROKERS_DIR") else None
    )
    if explicit is not None:
        # Explicit override (tests, custom sets): that directory only, strict.
        _registry = {b.slug: b for b in load_all_brokers(explicit)} if explicit.exists() else {}
        _loaded = True
        return

    merged = {b.slug: b for b in load_all_brokers(_brokers_dir())}
    for b in _load_lenient(imported_dir()):
        # A registry row for a broker we have a hand-built definition of adds its contact and
        # registry facts; it must not throw away the automation (form steps, re-search).
        merged[b.slug] = _keep_automation(merged[b.slug], b) if b.slug in merged else b
    merged.update({b.slug: b for b in _load_lenient(user_dir())})  # yours win outright

    merged = _add_extra_brokers(merged)
    merged = _apply_form_links(merged)
    merged = _apply_people_search(merged)
    merged = _apply_aliases(merged)

    from .contacts import apply_contact_overrides
    from .traits import apply_traits

    merged = apply_contact_overrides(merged)
    merged = apply_traits(merged)

    ov = load_overrides()
    for slug, broker in list(merged.items()):
        if slug in ov["disabled"]:
            merged[slug] = broker.model_copy(update={"enabled": False})
        elif slug in ov["enabled"]:
            merged[slug] = broker.model_copy(update={"enabled": True})
    _registry = merged
    _loaded = True


def _ensure_loaded() -> None:
    if not _loaded:
        load_registry()


def get_broker(slug: str) -> BrokerDef:
    _ensure_loaded()
    try:
        return _registry[slug]
    except KeyError:
        raise KeyError(f"Unknown broker slug: '{slug}'. Run `optout brokers list` to see options.")


def all_brokers() -> list[BrokerDef]:
    _ensure_loaded()
    return sorted(_registry.values(), key=lambda b: b.name)
