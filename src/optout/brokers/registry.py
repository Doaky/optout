"""In-memory broker catalog, populated from the brokers/ YAML directory.

Bundled definitions are loaded strictly. Two user-controlled layers are loaded
leniently (a bad file is reported, not fatal) and win over the bundled set:

1. ``<data dir>/imported/``   generated by ``optout brokers import``
2. ``<config dir>/brokers.d/``  hand-written fixes and additions

``<config dir>/overrides.yml`` then enables or disables brokers by slug.
"""

from __future__ import annotations

import os
from importlib.resources import files
from pathlib import Path

import yaml

from ..config import config_dir
from ..db import db_path
from .loader import load_all_brokers, load_broker
from .schema import BrokerDef

_registry: dict[str, BrokerDef] = {}
_loaded = False
load_errors: list[str] = []


def _brokers_dir() -> Path:
    """Return the directory containing broker YAML files.

    Priority:
    1. OPTOUT_BROKERS_DIR env var — lets users/tests override with a custom set.
    2. importlib.resources — finds the YAMLs bundled inside the installed package,
       works for both editable installs (real filesystem path) and wheel installs.
    """
    env = os.environ.get("OPTOUT_BROKERS_DIR")
    if env:
        return Path(env)
    return Path(str(files("optout").joinpath("data/brokers")))


def imported_dir() -> Path:
    return db_path().parent / "imported"


def user_dir() -> Path:
    return config_dir() / "brokers.d"


def overrides_path() -> Path:
    return config_dir() / "overrides.yml"


def load_overrides() -> dict[str, list[str]]:
    path = overrides_path()
    data = yaml.safe_load(path.read_text()) if path.exists() else None
    data = data if isinstance(data, dict) else {}
    return {k: sorted({str(x) for x in data.get(k) or []}) for k in ("enabled", "disabled")}


def set_enabled(slug: str, enabled: bool) -> None:
    ov = load_overrides()
    ov["enabled"] = [s for s in ov["enabled"] if s != slug]
    ov["disabled"] = [s for s in ov["disabled"] if s != slug]
    ov["enabled" if enabled else "disabled"].append(slug)
    path = overrides_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump({k: sorted(v) for k, v in ov.items()}))


def _load_lenient(directory: Path) -> list[BrokerDef]:
    found: list[BrokerDef] = []
    if not directory.exists():
        return found
    for yml in sorted(directory.glob("*.yml")):
        try:
            found.append(load_broker(yml))
        except (ValueError, yaml.YAMLError) as exc:
            load_errors.append(f"{yml.name}: {str(exc).splitlines()[0]}")
    return found


def load_registry(brokers_dir: Path | None = None) -> None:
    global _registry, _loaded
    load_errors.clear()
    explicit = brokers_dir or (
        Path(os.environ["OPTOUT_BROKERS_DIR"]) if os.environ.get("OPTOUT_BROKERS_DIR") else None
    )
    if explicit is not None:
        # Explicit override (tests, custom sets): that directory only, strict.
        _registry = {b.slug: b for b in load_all_brokers(explicit)} if explicit.exists() else {}
        _loaded = True
        return

    merged = {b.slug: b for b in load_all_brokers(_brokers_dir())}
    for layer in (imported_dir(), user_dir()):
        merged.update({b.slug: b for b in _load_lenient(layer)})

    ov = load_overrides()
    for slug, broker in list(merged.items()):
        if slug in ov["disabled"]:
            merged[slug] = broker.model_copy(update={"enabled": False})
        elif slug in ov["enabled"]:
            merged[slug] = broker.model_copy(update={"enabled": True})
    _registry = merged
    _loaded = True


def _ensure_loaded() -> None:
    if not _loaded:
        load_registry()


def get_broker(slug: str) -> BrokerDef:
    _ensure_loaded()
    try:
        return _registry[slug]
    except KeyError:
        raise KeyError(f"Unknown broker slug: '{slug}'. Run `optout brokers list` to see options.")


def all_brokers() -> list[BrokerDef]:
    _ensure_loaded()
    return sorted(_registry.values(), key=lambda b: b.name)
